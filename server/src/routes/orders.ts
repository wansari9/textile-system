import { Router, Request, Response } from 'express';
import pool from '../config/db';
import { authenticateToken, requireRole } from '../middleware/auth';

const router = Router();

// Orders are an admin-only area.
router.use(authenticateToken, requireRole('ADMIN'));

const GENDERS = ['MEN', 'WOMEN', 'BOYS', 'GIRLS', 'KIDS', 'UNISEX'];

// order_date is a DATE; return it as YYYY-MM-DD so the client never has to
// deal with a timezone-shifted timestamp.
const ORDER_COLUMNS = `product_id, order_no, to_char(order_date, 'YYYY-MM-DD') AS order_date,
  gender, product_name, style_code, color, size, order_quantity, daily_target, status,
  start_date, due_date, created_at, customer_id, customer_name,
  produced_to_date, remaining_qty, pct_complete, line_name, line_id, assignment_id`;

const todayISO = () => new Date().toISOString().slice(0, 10);

// Thrown inside a transaction so the catch block can roll back and answer
// with a proper status code instead of a generic 500.
const httpError = (status: number, message: string) => {
  const error: any = new Error(message);
  error.status = status;
  return error;
};

// GET /api/orders  (?status=&customer_id=&line_id=&from=&to=&search=)
// Orders are products; this exposes them with customer, progress and line.
router.get('/', async (req: Request, res: Response) => {
  const { status, customer_id, line_id, from, to, search } = req.query;
  try {
    const conditions: string[] = [];
    const params: any[] = [];

    if (status) {
      params.push(status);
      conditions.push(`status = $${params.length}`);
    }
    if (customer_id) {
      params.push(customer_id);
      conditions.push(`customer_id = $${params.length}`);
    }
    if (line_id) {
      params.push(line_id);
      conditions.push(
        `EXISTS (
           SELECT 1 FROM line_assignments la
           WHERE la.product_id = vw_orders.product_id
             AND la.status = 'ACTIVE'
             AND la.line_id = $${params.length}
         )`
      );
    }
    if (from) {
      params.push(from);
      conditions.push(`order_date >= $${params.length}`);
    }
    if (to) {
      params.push(to);
      conditions.push(`order_date <= $${params.length}`);
    }
    if (search) {
      params.push(`%${search}%`);
      conditions.push(
        `(order_no ILIKE $${params.length} OR product_name ILIKE $${params.length} OR customer_name ILIKE $${params.length})`
      );
    }

    const whereClause = conditions.length ? `WHERE ${conditions.join(' AND ')}` : '';
    const result = await pool.query(
      `SELECT ${ORDER_COLUMNS} FROM vw_orders ${whereClause} ORDER BY order_date DESC NULLS LAST, order_no DESC`,
      params
    );
    res.json({ success: true, data: result.rows });
  } catch (error: any) {
    console.error('List orders error:', error);
    res.status(500).json({ success: false, message: 'Failed to fetch orders' });
  }
});

// GET /api/orders/:id
router.get('/:id', async (req: Request, res: Response) => {
  try {
    const result = await pool.query(`SELECT ${ORDER_COLUMNS} FROM vw_orders WHERE product_id = $1`, [req.params.id]);
    if (!result.rows[0]) {
      return res.status(404).json({ success: false, message: 'Order not found' });
    }
    res.json({ success: true, data: result.rows[0] });
  } catch (error: any) {
    console.error('Get order error:', error);
    res.status(500).json({ success: false, message: 'Failed to fetch order' });
  }
});

// POST /api/orders
// One transaction creates an optional new customer, the order, and an optional
// immediate line assignment. The order number is generated by the database.
router.post('/', async (req: Request, res: Response) => {
  const {
    customer_id, customer,
    product_name, style_code, color, size, gender,
    order_quantity, daily_target, status, start_date, due_date, order_date,
    assign,
  } = req.body;

  if (!product_name || !order_quantity || !daily_target) {
    return res.status(400).json({
      success: false,
      message: 'product_name, order_quantity, and daily_target are required',
    });
  }
  if (!customer_id && !customer?.customer_name) {
    return res.status(400).json({
      success: false,
      message: 'Either customer_id or customer.customer_name is required',
    });
  }

  const normalizedGender = gender ? String(gender).toUpperCase() : 'UNISEX';
  if (!GENDERS.includes(normalizedGender)) {
    return res.status(400).json({
      success: false,
      message: `gender must be one of: ${GENDERS.join(', ')}`,
    });
  }

  const client = await pool.connect();
  try {
    await client.query('BEGIN');

    // 1. Resolve or create the customer.
    let customerId = customer_id ? Number(customer_id) : null;
    let createdCustomer: any = null;

    if (customerId) {
      const exists = await client.query(`SELECT customer_id FROM customers WHERE customer_id = $1`, [customerId]);
      if (!exists.rows[0]) {
        throw httpError(404, 'Customer not found');
      }
    } else {
      const created = await client.query(
        `INSERT INTO customers (customer_name, contact_person, phone, email, address)
         VALUES ($1, $2, $3, $4, $5)
         RETURNING customer_id, customer_name, contact_person, phone, email, address, is_active, created_at`,
        [
          customer.customer_name,
          customer.contact_person ?? null,
          customer.phone ?? null,
          customer.email ?? null,
          customer.address ?? null,
        ]
      );
      customerId = created.rows[0].customer_id;
      createdCustomer = created.rows[0];
    }

    // 2. Create the order (a product row). order_no is generated by the DB.
    const product = await client.query(
      `INSERT INTO products
         (customer_id, product_name, style_code, color, size, gender,
          order_quantity, daily_target, status, start_date, due_date, order_date)
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8, COALESCE($9, 'PENDING'), $10, $11, COALESCE($12, CURRENT_DATE))
       RETURNING product_id, order_no, gender, order_date`,
      [
        customerId, product_name, style_code ?? null, color ?? null, size ?? null,
        normalizedGender, order_quantity, daily_target, status ?? null,
        start_date ?? null, due_date ?? null, order_date ?? null,
      ]
    );
    const productId = product.rows[0].product_id;

    // 3. Optionally assign straight to a sewing line.
    let assignment: any = null;
    if (assign?.line_id) {
      const line = await client.query(
        `SELECT line_id, line_name, line_type FROM production_lines WHERE line_id = $1`,
        [assign.line_id]
      );
      if (!line.rows[0]) {
        throw httpError(404, 'Line not found');
      }
      if (line.rows[0].line_type !== 'SEWING') {
        throw httpError(400, 'Orders can only be assigned to SEWING lines');
      }

      const inserted = await client.query(
        `INSERT INTO line_assignments (line_id, product_id, daily_target, start_date, created_by)
         VALUES ($1, $2, $3, $4, $5)
         RETURNING assignment_id`,
        [
          assign.line_id,
          productId,
          assign.daily_target ?? daily_target,
          assign.start_date ?? start_date ?? todayISO(),
          (req as any).user.id,
        ]
      );

      await client.query(
        `UPDATE products SET status = 'ACTIVE' WHERE product_id = $1 AND status = 'PENDING'`,
        [productId]
      );

      assignment = inserted.rows[0];
    }

    // 4. Read the joined order row before committing so the response is complete.
    const order = await client.query(`SELECT ${ORDER_COLUMNS} FROM vw_orders WHERE product_id = $1`, [productId]);

    await client.query('COMMIT');
    res.status(201).json({
      success: true,
      data: order.rows[0],
      customer: createdCustomer,
      assignment,
    });
  } catch (error: any) {
    await client.query('ROLLBACK');
    if (error.status) {
      return res.status(error.status).json({ success: false, message: error.message });
    }
    console.error('Create order error:', error);
    res.status(500).json({ success: false, message: 'Failed to create order' });
  } finally {
    client.release();
  }
});

export default router;
